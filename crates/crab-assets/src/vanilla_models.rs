/// Returns a vanilla rest-pose model for a directly renderable Java layer builder.
pub(crate) fn geometry_for(
    name: &str,
    texture_width: u32,
    texture_height: u32,
) -> Option<EntityGeometry> {
    let model = model_for(name)?;
    let entries: Vec<&ModelCube> = MODELS.iter().filter(|cube| cube.model == model).collect();
    if entries.is_empty() {
        return None;
    }
    let (model_w, model_h) = model_texture(model);
    let mut bones: Vec<Bone> = Vec::new();
    for entry in entries {
        let index = bones
            .iter()
            .position(|bone| bone.name == entry.bone)
            .unwrap_or_else(|| {
                bones.push(Bone {
                    name: entry.bone.to_owned(),
                    pivot: entry.pivot,
                    rotation: entry.rotation,
                    cubes: Vec::new(),
                });
                bones.len() - 1
            });
        bones[index].cubes.push(Cube {
            origin: entry.origin,
            size: entry.size,
            uv: entry.uv,
            mirror: entry.mirror,
        });
    }
    let min_y = bones
        .iter()
        .flat_map(|bone| bone.cubes.iter().map(|cube| cube.origin[1]))
        .fold(f32::INFINITY, f32::min);
    if min_y.is_finite() && min_y != 0.0 {
        for bone in &mut bones {
            bone.pivot[1] -= min_y;
            for cube in &mut bone.cubes {
                cube.origin[1] -= min_y;
            }
        }
    }
    Some(EntityGeometry {
        texture_width: if model_w == 0 {
            texture_width as f32
        } else {
            model_w as f32
        },
        texture_height: if model_h == 0 {
            texture_height as f32
        } else {
            model_h as f32
        },
        bones,
    })
}
